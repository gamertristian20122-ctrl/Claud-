def glass_layer(rows, style, hi_rows=6):
    """The glass of a WINDOW grid, as its own image (G lead lines, H panes, k = dark gaps)."""
    g = WINDOW_GLASS[style]
    out = Image.new("RGBA", (len(rows[0]), len(rows)), (0, 0, 0, 0))
    px = out.load()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == "H":
                c = g["hi"] if (y < hi_rows and x < 8) else g["H"]
                if (x, y) in ((6, 9), (9, 9), (7, 12), (8, 12)):
                    c = g["accent"]
                px[x, y] = AR.rgb(c) + (255,)
            elif ch == "G":
                px[x, y] = AR.rgb(g["G"]) + (255,)
            elif ch == "k":
                px[x, y] = AR.rgb("#111111") + (255,)
    return out


