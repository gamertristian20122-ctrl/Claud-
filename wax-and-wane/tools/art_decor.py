def light_pool(w=48, h=64, lean=0.35, soft=5.0):
    """Coloured window light falling on the floor: a lancet shape leaning to the right (the
    moon is high on the left), with the window's cross mullion as darker bars.  Smooth alpha:
    used only as a PointLight2D texture."""
    a = np.zeros((h, w), np.float32)
    cx0 = w * 0.3
    for y in range(h):
        k = y / (h - 1)
        cx = cx0 + lean * y
        half = w * 0.14 + w * 0.05 * k
        top_round = min(1.0, y / 10.0)
        for x in range(w):
            d = abs(x + 0.5 - cx)
            v = np.clip((half - d) / soft + 0.5, 0, 1) * (0.35 + 0.65 * top_round)
            # mullions: one vertical, one horizontal bar
            if abs(x + 0.5 - cx) < 1.2:
                v *= 0.55
            if abs(y - h * 0.45) < 1.5:
                v *= 0.6
            fade = 1.0 - max(0.0, (k - 0.75) / 0.25) ** 1.5
            a[y, x] = v * fade
    out = np.zeros((h, w, 4), np.uint8)
    out[:, :, :3] = 255
    out[:, :, 3] = np.clip(a * 255, 0, 255).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


def light_soft(size=64, inner=0.0):
    """A small soft radial glow for wall lights (cheaper than the shared 256 px light)."""
    a = np.zeros((size, size), np.float32)
    c = (size - 1) / 2
    for y in range(size):
        for x in range(size):
            d = math.hypot(x - c, y - c) / c
            a[y, x] = max(0.0, 1.0 - d) ** 1.6
    out = np.zeros((size, size, 4), np.uint8)
    out[:, :, :3] = 255
    out[:, :, 3] = np.clip(a * 255, 0, 255).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


