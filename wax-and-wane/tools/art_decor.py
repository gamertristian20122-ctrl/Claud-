def G(text):
    return AR.G(text)


def img(rows, pal=P):
    try:
        return AR.grid(rows, pal)
    except (KeyError, AssertionError) as e:
        raise SystemExit("bad grid starting %r...: %s" % (rows[:3], e))


def flip(im):
    return im.transpose(Image.FLIP_LEFT_RIGHT)


def stone(im, theme):
    """Remap the base stone ramp to the theme's wall colours (like the room walls)."""
    return AR.remap(im, AR.THEMES[theme]["wall"])


def layer(*parts, size=None):
    """Composite [(image, x, y), ...] onto one transparent canvas."""
    if size is None:
        size = parts[0][0].size
    out = Image.new("RGBA", size, (0, 0, 0, 0))
    for im, x, y in parts:
        out.alpha_composite(im, (x, y))
    return out


