def web(seed):
    """A floor cobweb: crooked spokes from an off-centre hub and two sagging rings."""
    import random as _r
    rng = _r.Random(seed)
    im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = im.load()
    hub = (7 + rng.randint(-1, 1), 7 + rng.randint(-1, 1))
    n = rng.randint(7, 9)
    base = rng.random() * math.tau
    spokes = []
    for i in range(n):
        a = base + i * math.tau / n + rng.uniform(-0.25, 0.25)
        spokes.append(a)

    def line(x0, y0, x1, y1, col, skip=0.0):
        steps = int(max(abs(x1 - x0), abs(y1 - y0))) + 1
        for k in range(steps + 1):
            t = k / max(1, steps)
            x, y = round(x0 + (x1 - x0) * t), round(y0 + (y1 - y0) * t)
            if 0 <= x < 16 and 0 <= y < 16 and rng.random() >= skip:
                px[x, y] = AR.rgb(col) + (255,)

    for a in spokes:
        r = rng.uniform(8.5, 11.0)
        line(hub[0], hub[1], hub[0] + math.cos(a) * r, hub[1] + math.sin(a) * r, P["m"], 0.08)
    for rr, col in ((3.2, P["n"]), (6.3, P["m"])):
        pts = [(hub[0] + math.cos(a) * rr * rng.uniform(0.85, 1.1), hub[1] + math.sin(a) * rr * rng.uniform(0.85, 1.1)) for a in spokes]
        for i in range(n):
            if rng.random() < 0.85:
                line(*pts[i], *pts[(i + 1) % n], col, 0.12)
    px[hub[0], hub[1]] = AR.rgb(P["n"]) + (255,)
    return im


