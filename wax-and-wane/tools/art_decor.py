def rock_soot():
    """A soot-blackened rock with a glowing ember crack: it hides a bomb."""
    base = AR.grid(AR.ROCK, AR.PROP)
    im = AR.remap(base, {"#d3bfa9": "#545454", "#aa8d7a": "#3f3f3f", "#775c55": "#333333",
                         "#483b3a": "#2b2929"}).copy()
    px = im.load()
    crack = [(7, 5, "A"), (7, 6, "R"), (8, 7, "Z"), (8, 8, "R"), (9, 9, "A"), (7, 9, "R"),
             (6, 10, "A"), (10, 10, "R"), (4, 6, "i"), (5, 5, "i"), (11, 11, "Z")]
    for x, y, ch in crack:
        px[x, y] = AR.rgb(P[ch]) + (255,)
    return im


