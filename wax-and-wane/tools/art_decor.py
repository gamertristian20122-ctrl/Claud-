def preview(made, theme):
    room = Image.open(os.path.join(AR.OUT, "room_%s.png" % theme)).convert("RGBA")
    im = AR.on_bg(room)
    walls, props, decals = PREVIEW[theme]
    for n, x, y in decals:
        im.alpha_composite(made[n], (x, y))
    for n, x, y in walls:
        im.alpha_composite(made[n], (x, y))
        if n.endswith("_glass") is False and n.startswith("wall_window"):
            im.alpha_composite(made[n + "_glass"], (x, y))
    for n, c, r in sorted(props, key=lambda p: p[2]):
        spr = made[n]
        x = 16 + c * 16 + 8 - spr.size[0] // 2
        y = 32 + r * 16 + 16 - spr.size[1]
        im.alpha_composite(spr, (x, y))
        if n == "prop_hearth":
            im.alpha_composite(made["fire_f0"], (x + 3, y - 1))
    return im


def review(made, outdir):
    os.makedirs(outdir, exist_ok=True)
    for th in THEMES:
        pv = preview(made, th)
        pv.resize((pv.size[0] * 4, pv.size[1] * 4), Image.NEAREST).save(os.path.join(outdir, "pv_%s.png" % th))
        pv.crop((0, 0, 136, 96)).resize((136 * 8, 96 * 8), Image.NEAREST).save(os.path.join(outdir, "pv_%s_tl.png" % th))
        pv.crop((136, 0, 272, 96)).resize((136 * 8, 96 * 8), Image.NEAREST).save(os.path.join(outdir, "pv_%s_tr.png" % th))
    items = sorted(made.items())
    AR.contact([(n, AR.on_bg(im, (72, 59, 58, 255))) for n, im in items],
               os.path.join(outdir, "decor_8x.png"), scale=8, cols=8)
    AR.contact([(n, AR.on_bg(im, (12, 10, 12, 255))) for n, im in items if n.startswith(("wall_", "side_", "sconce_", "flame_", "fire_"))],
               os.path.join(outdir, "decor_dark_8x.png"), scale=8, cols=8)


def main():
    review_dir = None
    for a in sys.argv[1:]:
        if a == "--review":
            review_dir = "/tmp/claude-0/review_decor"
        elif a.startswith("--out="):
            review_dir = a.split("=", 1)[1]
    pal = AR.sheet_palette()
    made = build()
    os.makedirs(os.path.join(OUT, "light"), exist_ok=True)
    for name, im in made.items():
        a = np.array(im)
        assert set(np.unique(a[:, :, 3])) <= {0, 255}, name + " has semi-transparent pixels"
        cols = {tuple(int(v) for v in p[:3]) for p in a.reshape(-1, 4) if p[3]}
        bad = cols - pal
        assert not bad, "%s uses colours outside the 0x72 palette: %s" % (
            name, ["#%02x%02x%02x" % c for c in bad])
        im.save(os.path.join(OUT, name + ".png"), optimize=True)
    for name, im in lights().items():
        im.save(os.path.join(OUT, name + ".png"), optimize=True)
    if review_dir:
        review(made, review_dir)
    print("wrote %d decor sprites + light textures to %s" % (len(made), OUT))


if __name__ == "__main__":
    main()
