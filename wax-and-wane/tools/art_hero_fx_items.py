# Rising smoke wisp 9x12: one ribbon, the wave travels up 3 rows per frame so
# the 4 frames loop. Brighter + thicker at the bottom, thin and dim on top.
def smoke_frames():
    frames = []
    for f in range(4):
        rows = [["."] * 9 for _ in range(12)]
        xs = []
        for y in range(12):
            ph = 2 * math.pi * (y + 3 * f) / 12.0
            amp = 0.6 + 1.6 * (11 - y) / 11.0
            xs.append(int(round(3.5 + amp * math.sin(ph))))
        for y in range(12):
            x = xs[y]
            if y <= 2:            # dispersing top: thin + dim
                rows[y][x] = "i"
            elif y <= 8:          # body: 2 px, lit on the left
                rows[y][x] = "S"
                rows[y][x + 1] = "i"
            else:                 # thin thread near the wick
                rows[y][x] = "S"
            if y < 11 and abs(xs[y + 1] - x) > 1:   # keep the ribbon connected
                mid = (x + xs[y + 1]) // 2
                if rows[y][mid] == ".":
                    rows[y][mid] = "i" if y <= 2 else "S"
        frames.append(grid(["".join(r) for r in rows], 9, 12))
    return frames


def scorch():
    W, H = 32, 20
    cx, cy = 15.5, 9.5
    rows = [["."] * W for _ in range(H)]
    for y in range(H):
        for x in range(W):
            dx, dy = (x + 0.5 - cx) / 14.5, (y + 0.5 - cy) / 9.0
            a = math.atan2(dy, dx)
            rr = math.hypot(dx, dy)
            edge = 1 + 0.10 * math.sin(5 * a + 0.7) + 0.07 * math.sin(9 * a + 2.1) - 0.08
            if rr < edge * 0.45:
                rows[y][x] = "1"
            elif rr < edge * 0.75:
                rows[y][x] = "k"
            elif rr < edge:
                rows[y][x] = "3"
    return grid(["".join(r) for r in rows], W, H)


def soft_light():
    S = 256
    im = Image.new("RGBA", (S, S), (255, 255, 255, 0))
    px = im.load()
    c = (S - 1) / 2.0
    for y in range(S):
        for x in range(S):
            d = math.hypot(x - c, y - c) / (S / 2.0)
            t = max(0.0, min(1.0, 1.0 - d))
            a = t * t * (3 - 2 * t)
            px[x, y] = (255, 255, 255, int(round(255 * a)))
    return im


