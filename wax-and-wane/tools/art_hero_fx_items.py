# Puff-cluster renderer (explosion, poof): each puff is a pixel-exact disc,
# cel-shaded in 3 bands by its own top-left normal. Later puffs sit in front.
def puffs(W, H, plist, ramp):
    """Each puff = pixel-exact disc, cel-shaded like a ball lit from the
    top-left: a highlight disc pushed up-left, a shadow crescent bottom-right."""
    rows = [["."] * W for _ in range(H)]
    for (cx, cy, r, lvl) in plist:
        for y in range(H):
            for x in range(W):
                X, Y = x + 0.5, y + 0.5
                if (X - cx) ** 2 + (Y - cy) ** 2 > r * r:
                    continue
                hx, hy, hr = cx - r * 0.32, cy - r * 0.32, r * 0.62
                sx, sy, sr = cx - r * 0.22, cy - r * 0.22, r * 0.92
                if (X - hx) ** 2 + (Y - hy) ** 2 <= hr * hr:
                    band = 0
                elif (X - sx) ** 2 + (Y - sy) ** 2 <= sr * sr:
                    band = 1
                else:
                    band = 2
                rows[y][x] = ramp[min(len(ramp) - 1, lvl + band)]
    return rows_to_str(rows)


def rows_to_str(rows):
    return ["".join(r) for r in rows]


def ring(cx, cy, dist, n, r, lvl, rot=0.0, squash=1.0, wob=None):
    out = []
    for k in range(n):
        a = rot + 2 * math.pi * k / n
        d = dist * (1 + (wob[k % len(wob)] if wob else 0))
        out.append((cx + math.cos(a) * d, cy + math.sin(a) * d * squash, r, lvl))
    return out


