def rgba(h, a=255):
    return (int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16), a)


def parse(block):
    rows = [ln.strip() for ln in block.strip("\n").splitlines()]
    return [r for r in rows if r]


def grid(block, w=None, h=None, remap=None):
    """Char grid -> RGBA image. Rows may be given as a block string or list."""
    rows = parse(block) if isinstance(block, str) else list(block)
    W = w or max(len(r) for r in rows)
    H = h or len(rows)
    rows = [r.ljust(W, ".") for r in rows] + ["." * W] * (H - len(rows))
    for r in rows:
        assert len(r) == W, (len(r), W, r)
    im = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    px = im.load()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if remap and ch in remap:
                ch = remap[ch]
            col = PAL[ch]
            if col:
                px[x, y] = rgba(col)
    return im


def outline(im, col="#222222"):
    """Add a 1 px outline around every opaque shape (4-neighbour, like 0x72)."""
    W, H = im.size
    src = im.load()
    out = im.copy()
    o = out.load()
    c = rgba(col)
    for y in range(H):
        for x in range(W):
            if src[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                X, Y = x + dx, y + dy
                if 0 <= X < W and 0 <= Y < H and src[X, Y][3]:
                    o[x, y] = c
                    break
    return out


def save(im, *path):
    p = os.path.join(ART, *path)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    im.save(p)
    OUT.append(p)
    return im


