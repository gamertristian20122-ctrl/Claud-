BG = (0x1a, 0x14, 0x18, 255)


def sheet(rows, S=8, pad=12, bg=BG):
    rows = [r for r in rows if r]
    Wt = max(sum(i.width * S + pad for i in r) + pad for r in rows)
    Ht = sum(max(i.height for i in r) * S + pad for r in rows) + pad
    out = Image.new("RGBA", (Wt, Ht), bg)
    y = pad
    for r in rows:
        x = pad
        h = max(i.height for i in r)
        for i in r:
            out.alpha_composite(i.resize((i.width * S, i.height * S), Image.NEAREST),
                                (x, y + (h - i.height) * S))
            x += i.width * S + pad
        y += h * S + pad
    return out


def ox(name):
    return Image.open(os.path.join(OX72, name + ".png")).convert("RGBA")


def on_floor(sprite, tiles=("floor_1", "floor_2", "floor_3", "floor_5"), cols=2, rows=2):
    W, H = 16 * cols, 16 * rows
    bg = Image.new("RGBA", (W, H))
    k = 0
    for y in range(rows):
        for x in range(cols):
            bg.alpha_composite(ox(tiles[k % len(tiles)]), (x * 16, y * 16))
            k += 1
    bg.alpha_composite(sprite, ((W - sprite.width) // 2, (H - sprite.height) // 2))
    return bg


