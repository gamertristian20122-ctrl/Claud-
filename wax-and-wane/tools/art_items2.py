def icon(name):
    return outline(grid(ICONS[name], 16, 16))


def framed(rows, remap=None):
    return outline(grid(rows, remap=remap))


def pad(im, n=1):
    out = Image.new("RGBA", (im.width + 2 * n, im.height + 2 * n))
    out.alpha_composite(im, (n, n))
    return out


def build():
    for n in NEW_RELICS + NEW_KEEPSAKES:
        save(icon(n), "items", n + ".png")
    for k, frames in FAMS.items():
        for i, g in enumerate(frames):
            save(outline(pad(grid(g))), "items", "fam_%s_f%d.png" % (k, i))
    for k, frames in SHOTS.items():
        for i, g in enumerate(frames):
            im = grid(g)
            if k in ("ghost", "ring"):
                im = pad(im)  # soft-edged things keep no outline, like the 0x72 bullets
            else:
                im = outline(pad(im))
            save(im, "items", "fx", "%s_f%d.png" % (k, i))
            if k == "bigflame":
                save(outline(pad(grid(g, remap=BLUE))), "items", "fx", "bigflame_blue_f%d.png" % i)
    save(outline(pad(grid(JUG))), "items", "fx", "jug.png")
    for k, g in COSTUME.items():
        save(outline(pad(grid(g))), "items", "costume", k + ".png")
    for i, g in enumerate(PUFFS):
        save(pad(grid(g)), "items", "costume", "puff_f%d.png" % i)


def review(d):
    os.makedirs(d, exist_ok=True)
    L = lambda *p: Image.open(os.path.join(ART, *p)).convert("RGBA")
    old = [L("items", n + ".png") for n in base.ICON_ORDER + base.KEEPSAKE_ORDER]
    new = [L("items", n + ".png") for n in NEW_RELICS + NEW_KEEPSAKES]
    allic = old + new
    rows = [allic[i:i + 12] for i in range(0, len(allic), 12)]
    sheet(rows, S=6).save(os.path.join(d, "all_icons_6x.png"))
    sheet(rows, S=1, pad=3).save(os.path.join(d, "all_icons_1x.png"))
    sheet(rows, S=2, pad=4).save(os.path.join(d, "all_icons_2x.png"))
    sheet([[on_floor(i, cols=1, rows=1) for i in allic[k:k + 16]] for k in range(0, len(allic), 16)],
          S=3, pad=4).save(os.path.join(d, "all_icons_onfloor_3x.png"))
    fam = []
    for k, frames in FAMS.items():
        fam += [L("items", "fam_%s_f%d.png" % (k, i)) for i in range(len(frames))]
    shots = []
    for k, frames in SHOTS.items():
        shots += [L("items", "fx", "%s_f%d.png" % (k, i)) for i in range(len(frames))]
    shots += [L("items", "fx", "jug.png"), L("fx", "ember_f0.png"), L("fx", "ember_big_f0.png")]
    cos = [L("items", "costume", k + ".png") for k in COSTUME] + [L("items", "costume", "puff_f%d.png" % i) for i in range(3)]
    sheet([fam + [ox("imp_idle_anim_f0")], shots, cos], S=6).save(os.path.join(d, "helpers_fx_costume_6x.png"))
    sheet([[on_floor(f, cols=1, rows=1) for f in fam] + [on_floor(s, cols=1, rows=1) for s in shots[:8]]],
          S=4, pad=4).save(os.path.join(d, "helpers_onfloor_4x.png"))


def main():
    build()
    if "--review" in sys.argv:
        review(sys.argv[sys.argv.index("--review") + 1])
    print("wrote %d files" % len(base.OUT))


if __name__ == "__main__":
    main()
