def grid_img(block):
    """A grid with no outline pass (fx): every char is a filled pixel or '.'."""
    return from_grid(block, outline=False)


# --------------------------------------------------------------------------- the Slam ring

RING_RADII = [9, 16, 23, 30, 37, 43]
RING_COLS = [("w", "y"), ("w", "y"), ("y", "o"), ("y", "o"), ("o", "r"), ("r", "R")]


def ring_frame(i, size=91):
    """A pixel ring: a 2 px band (outer colour, inner colour) with a 1 px dark rim on both sides;
    the last frames thin to 1 px. Distances are measured to pixel centres (no anti-aliasing)."""
    r = RING_RADII[i]
    outer, inner = RING_COLS[i]
    c = size // 2
    g = [["."] * size for _ in range(size)]
    thick = 2 if i < 5 else 1
    for y in range(size):
        for x in range(size):
            d = math.hypot(x - c, y - c)
            if r - thick <= d < r:
                g[y][x] = outer if d >= r - 1 else inner
    # dark rim: transparent pixels touching the band (4-neighbours)
    rim = []
    for y in range(size):
        for x in range(size):
            if g[y][x] != ".":
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                xx, yy = x + dx, y + dy
                if 0 <= xx < size and 0 <= yy < size and g[yy][xx] not in ".K":
                    rim.append((x, y))
                    break
    for x, y in rim:
        g[y][x] = "K"
    return from_grid("\n".join("".join(r) for r in g), outline=False)


# --------------------------------------------------------------------------- run

def check(name, im, sheet):
    for p in im.get_flattened_data():
        if p[3] == 0:
            continue
        assert p[3] == 255, "%s: semi-transparent pixel %r" % (name, p)
        assert tuple(p[:3]) in sheet, "%s: off-palette pixel %r" % (name, p)


def main():
    review = None
    if "--review" in sys.argv:
        review = sys.argv[sys.argv.index("--review") + 1]
    for name, block in [("icon_skip", ICON_SKIP), ("icon_sparkler", ICON_SPARKLER), ("icon_slam", ICON_SLAM),
                        ("icon_blink", ICON_BLINK), ("icon_flare", ICON_FLARE), ("icon_snuff", ICON_SNUFF)]:
        im = from_grid(block)
        assert im.size == (16, 16), (name, im.size)
        save(im, name)
    for i, b in enumerate(SPARK):
        save(grid_img(b), "spark_f%d" % i)
    for i, b in enumerate(BURST):
        save(grid_img(b), "burst_f%d" % i)
    for i in range(len(RING_RADII)):
        save(ring_frame(i), "ring_f%d" % i)
    for i, b in enumerate(BLINK):
        save(grid_img(b), "blink_f%d" % i)
    for i, b in enumerate(RELIGHT):
        save(from_grid(b, outline=True), "relight_f%d" % i)
    for i, b in enumerate(BLACKFLAME):
        save(grid_img(b), "blackflame_f%d" % i)
    sheet = art_rooms.sheet_palette()
    for name, im in WRITTEN:
        check(name, im, sheet)
    print("moves: wrote %d images to %s (all on the 0x72 palette)" % (len(WRITTEN), OUT))
    if review:
        os.makedirs(review, exist_ok=True)
        for bg_name, bg in [("hud", (0x21, 0x14, 0x1B, 255)), ("floor", (0x48, 0x3B, 0x3A, 255))]:
            k = 8
            pad = 4
            x = pad
            hmax = 0
            items = [im for n, im in WRITTEN if not n.startswith("ring_")]
            total_w = sum(im.width + pad for im in items) + pad
            sheet_im = Image.new("RGBA", (total_w, 24), bg)
            for im in items:
                sheet_im.alpha_composite(im, (x, (24 - im.height) // 2))
                x += im.width + pad
                hmax = max(hmax, im.height)
            sheet_im.resize((sheet_im.width * k, sheet_im.height * k), Image.NEAREST).save(
                os.path.join(review, "moves_%s.png" % bg_name))
            rings = [im for n, im in WRITTEN if n.startswith("ring_")]
            rs = Image.new("RGBA", (len(rings) * 95 + 4, 95), bg)
            for i, im in enumerate(rings):
                rs.alpha_composite(im, (4 + i * 95, 2))
            rs.resize((rs.width * 3, rs.height * 3), Image.NEAREST).save(os.path.join(review, "rings_%s.png" % bg_name))
        print("moves: review sheets in", review)


if __name__ == "__main__":
    main()
