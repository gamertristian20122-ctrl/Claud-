ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "art", "moves")
OUTLINE = "#222222"

PAL = dict(UI_PAL)
PAL.update({
    "n": "#5956bd", "t": "#72d6ce", "b": "#5698cc", "z": "#dc4a7b", "N": "#417089",
    # no-outline variants (sparks, smoke, motion lines): same colours, skipped by the outline pass
    "+": "#facb3e", "-": "#ee8e2e", "*": "#fdf7ed", "=": "#b6cbcf", "~": "#7b8994", "^": "#cae6f5",
    "_": "#da4e38",
})
NO_OUTLINE = set("+-*=~^_")
WRITTEN = []


def rows(block):
    out = [r for r in (ln.strip() for ln in block.strip("\n").splitlines()) if r]
    w = max(len(r) for r in out)
    for r in out:
        assert len(r) == w, ("ragged row", r)
    return out


def from_grid(block, outline=True):
    g = [list(r) for r in rows(block)]
    h, w = len(g), len(g[0])
    if outline:
        add = []
        for y in range(h):
            for x in range(w):
                if g[y][x] != ".":
                    continue
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    xx, yy = x + dx, y + dy
                    if 0 <= xx < w and 0 <= yy < h and g[yy][xx] not in ".k" and g[yy][xx] not in NO_OUTLINE:
                        add.append((x, y))
                        break
        for x, y in add:
            g[y][x] = "k"
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = im.load()
    for y in range(h):
        for x in range(w):
            ch = g[y][x]
            if ch == ".":
                continue
            col = OUTLINE if ch == "k" else PAL[ch]
            px[x, y] = (int(col[1:3], 16), int(col[3:5], 16), int(col[5:7], 16), 255)
    return im


def save(im, name):
    os.makedirs(OUT, exist_ok=True)
    p = os.path.join(OUT, name + ".png")
    im.save(p)
    WRITTEN.append((name, im))


